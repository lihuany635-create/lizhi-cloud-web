  function loadScripts(list){
    // async=false 讓動態加入的 script 依加入順序執行，同時可平行下載。
    return Promise.all(list.map(src=>new Promise((resolve,reject)=>{
      const el=document.createElement("script");
      el.src=src;el.async=false;
      el.onload=resolve;
      el.onerror=()=>reject(new Error("載入失敗："+src));
      document.head.append(el);
    })));
  }
  function ensure(group){
    if(!GROUPS[group])return Promise.resolve();
    if(!pending.has(group)){
      pending.set(group,loadScripts(GROUPS[group]).then(()=>{activators[group]?.();ready.add(group);}).catch(error=>{pending.delete(group);throw error;}));
    }
    return pending.get(group);
  }
